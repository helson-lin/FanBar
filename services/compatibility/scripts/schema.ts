import { readFileSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import {
  DIAGNOSTIC_MAXIMUM_BYTES, DIAGNOSTIC_POLICY_VERSION, DIAGNOSTIC_RETENTION_DAYS,
  MAXIMUM_REPORT_BYTES, policy, POLICY_VERSION, RETENTION_DAYS,
} from '../src/policy.ts';
import { reportSchema } from '../src/schema.ts';
const text = JSON.stringify({
  ...z.toJSONSchema(reportSchema, { target: 'draft-7' }),
  title: 'FanBar compatibility report v1',
  description: 'Strict upload allow-list. Additional semantic evidence checks are documented in services/compatibility/PRIVACY.md.',
}, null, 2) + '\n';
for (const file of ['../../contracts/compatibility-report.schema.json', 'web/public/report-schema.json']) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== text) throw new Error(`Schema drift: ${file}`);
  } else { writeFileSync(file, text); }
}

const policyFile = '../../contracts/compatibility-policy.example.json';
const policyText = JSON.stringify(policy('https://report.getfanbar.com', POLICY_VERSION), null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(policyFile, 'utf8') !== policyText) throw new Error('Policy fixture drift');
} else { writeFileSync(policyFile, policyText); }

// Shared display-only names: no extra device metadata is accepted in uploads.
const modelNames = readFileSync('../../contracts/mac-model-names.json', 'utf8');
for (const file of ['../../Sources/FanBar/Resources/mac-model-names.json', 'web/src/lib/mac-model-names.json']) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== modelNames) throw new Error(`Model names drift: ${file}`);
  } else { writeFileSync(file, modelNames); }
}

// Values the native client validates with strict equality. Tests/FanBarTests/ServiceContractTests.swift
// compares Sources/FanBarShared/ServiceContract.swift with this file, so a server-only change fails CI.
const constantsFile = '../../contracts/service-constants.json';
const constantsText = JSON.stringify({
  $comment: 'Generated by services/compatibility/scripts/schema.ts. Do not edit by hand.',
  compatibility: { policyVersion: POLICY_VERSION, retentionDays: RETENTION_DAYS, maximumReportBytes: MAXIMUM_REPORT_BYTES },
  diagnostics: { policyVersion: DIAGNOSTIC_POLICY_VERSION, retentionDays: DIAGNOSTIC_RETENTION_DAYS, maximumBytes: DIAGNOSTIC_MAXIMUM_BYTES },
}, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(constantsFile, 'utf8') !== constantsText) throw new Error('Service constants drift: run npm run schema');
} else { writeFileSync(constantsFile, constantsText); }
